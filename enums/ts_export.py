"""
Generates frontend/src/types/enums.ts from enums/domain.py, so the frontend's
union types come from the same definition as the Python enums.

    python -m enums.ts_export          # rewrite the file
    python -m enums.ts_export --check  # exit 1 if it is out of date

tests/test_enums.py runs the same comparison, so a changed enum without a
regenerated file fails the suite.
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

from enums.domain import TS_EXPORTED

TS_PATH = Path(__file__).resolve().parent.parent / "frontend" / "src" / "types" / "enums.ts"

_HEADER = (
    "// GENERATED by `python -m enums.ts_export` from enums/domain.py - do not edit by hand.\n"
    "// A test fails if this file is out of date.\n"
)


def _const_name(cls_name: str) -> str:
    # MatchFormat -> MATCH_FORMATS, SimStatus -> SIM_STATUSES
    snake = re.sub(r"(?<!^)(?=[A-Z])", "_", cls_name).upper()
    return snake + ("ES" if snake.endswith(("S", "SH", "CH", "X")) else "S")


def render() -> str:
    blocks = []
    for cls in TS_EXPORTED:
        const = _const_name(cls.__name__)
        values = ", ".join(f"'{v}'" for v in cls.values())
        blocks.append(
            f"export const {const} = [{values}] as const\n"
            f"export type {cls.__name__} = (typeof {const})[number]\n"
        )
    return _HEADER + "\n" + "\n".join(blocks)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.strip().splitlines()[0])
    ap.add_argument("--check", action="store_true", help="exit 1 if the file is out of date")
    args = ap.parse_args(argv)
    expected = render()
    current = TS_PATH.read_text(encoding="utf-8") if TS_PATH.exists() else ""
    if args.check:
        if current != expected:
            print(f"{TS_PATH} is out of date - run: python -m enums.ts_export", file=sys.stderr)
            return 1
        return 0
    TS_PATH.write_text(expected, encoding="utf-8")
    print(f"wrote {TS_PATH}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
